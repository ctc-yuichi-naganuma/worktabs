function createIcons({ document }) {
  function icon(name) {
    const svg = document.createElementNS(SVG_NS, 'svg');
    svg.setAttribute('class', 'icon');
    svg.setAttribute('viewBox', '0 0 16 16');
    svg.setAttribute('aria-hidden', 'true');
    for (const [tag, attributes] of ICONS[name]) {
      const part = document.createElementNS(SVG_NS, tag);
      for (const [key, value] of Object.entries(attributes)) part.setAttribute(key, String(value));
      svg.append(part);
    }
    return svg;
  }

  // A service's logo (LOGOS), in the text color as the icons are.
  function logo(name) {
    const svg = document.createElementNS(SVG_NS, 'svg');
    svg.setAttribute('class', 'icon');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('aria-hidden', 'true');
    const path = document.createElementNS(SVG_NS, 'path');
    path.setAttribute('class', 'fill');
    path.setAttribute('d', LOGOS[name]);
    svg.append(path);
    return svg;
  }

  function agentIcon(agent) {
    const name = agent === 'codex' ? 'codex' : 'claude';
    const mark = logo(name);
    mark.classList.add('agent-icon', name);
    return mark;
  }

  return { icon, logo, agentIcon };
}

